"""
Демонстрационный stages.py — пример многоэтапной установки, где чередуются
USB-флешка, ручные действия на самой магнитоле и ADB. Такой сценарий нужен,
когда на магнитоле сначала нужно обновить прошивку с флешки, потом что-то
доустановить по ADB, а потом ещё раз вручную поставить APK через файловый
менеджер — всё это одной последовательностью в окне "Установка по этапам...".

STAGES — обязательный список этапов, в порядке выполнения. Каждый этап —
словарь:
    type:        "usb" | "adb" | "manual"
    title:       короткое название этапа (для списка в мастере)
    run:         функция run(ctx), обязательна для "usb" и "adb", не нужна
                 для "manual"
                     - "usb": ctx — это UsbContext (как в usb_install.py)
                     - "adb": ctx — это InstallContext (как в install.py)
    instruction: (опц.) имя html-файла рядом с этим скриптом — если нужна
                 инструкция с оформлением/скриншотами для этого этапа
    description: (опц.) обычный текст-инструкция, если html не нужен

Мастер выполняет этапы не строго по порядку "по кнопке" — пользователь сам
переключается между ними в списке слева и жмёт подходящее действие (для usb
открывается обычное окно флешки, для adb — запуск прямо в мастере, для
manual — просто отметка "выполнено"). Это удобно, если какой-то шаг нужно
повторить (например, флешка не заработала с первого раза).
"""


def _usb_firmware(ctx):
    ctx.log("Копирую файлы прошивки на флешку")
    firmware_dir = ctx.file("firmware")
    if firmware_dir.exists():
        ctx.copy_dir(firmware_dir, "")
    else:
        ctx.log(f"(демо) папки {firmware_dir} нет — пропускаю копирование прошивки")


def _adb_install_apps(ctx):
    ctx.log("Устанавливаю приложения по ADB после обновления прошивки")
    if ctx.selected_apks:
        ctx.install_selected_apks()
    else:
        ctx.log("Ни одно приложение не отмечено галочкой")


def _usb_apk_for_manual_install(ctx):
    ctx.log("Копирую APK на флешку для установки через файловый менеджер магнитолы")
    ctx.copy_selected_apks("")


